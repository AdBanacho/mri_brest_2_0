"""Generate the embedded data files so index.html works from file://.

    python sync_data.py          # regenerate workflow-data.js and config-data.js
    python sync_data.py --check  # exit 1 if either file is out of date (for CI / pre-commit)

* workflow-data.js  <- workflow.json (hand-written analysis; the source of truth for stages)
* config-data.js    <- the configuration space, computed by config_space.py with the project's
                       own fields.tsv, schema.validate_combinations, cli.required_inputs and the
                       shipped experiment.conf / configs/*.conf / configs/campaign/*.conf. Re-run after changing any of them.

Never edit the generated .js files by hand. Standard library only (mribreast.config.schema and
mribreast.cli need only the standard library at import time).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # never leave __pycache__ in the viewer or src/
HERE = Path(__file__).resolve().parent
SOURCE = HERE / "workflow.json"
WORKFLOW_TARGET = HERE / "workflow-data.js"
CONFIG_TARGET = HERE / "config-data.js"


def render_workflow() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))  # validates the JSON
    stage_ids = {s["id"] for s in data["stages"]}
    for edge in data["edges"]:
        for end in ("from", "to"):
            if edge[end] not in stage_ids:
                raise SystemExit(f"edge {edge} refers to unknown stage {edge[end]!r}")
    if set(data["playOrder"]) != stage_ids:
        raise SystemExit("playOrder must list every stage exactly once")
    body = json.dumps(data, ensure_ascii=False, indent=1)
    return "// GENERATED from workflow.json by sync_data.py - do not edit by hand.\n" \
           f"window.WORKFLOW = {body};\n"


def render_config_space() -> str:
    sys.path.insert(0, str(HERE))
    import config_space  # imports the project's own schema / cli from ../src

    data = config_space.build()
    stage_ids = {s["id"] for s in json.loads(SOURCE.read_text(encoding="utf-8"))["stages"]}
    for notes in (x for x in data["shared"] if isinstance(x, dict)):
        unknown = set(notes) - stage_ids
        if unknown:
            raise SystemExit(f"config_space stage notes refer to unknown stages {sorted(unknown)}")
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    return ("// GENERATED by sync_data.py (config_space.py) from fields.tsv, schema.validate_combinations,\n"
            "// cli.required_inputs and the shipped *.conf files - do not edit by hand.\n"
            f"window.CONFIG_SPACE = {body};\n")


def main(argv: list[str]) -> int:
    outputs = {WORKFLOW_TARGET: render_workflow(), CONFIG_TARGET: render_config_space()}
    if "--check" in argv:
        stale = [p.name for p, text in outputs.items()
                 if (p.read_text(encoding="utf-8") if p.exists() else "") != text]
        if stale:
            print(f"out of date: {', '.join(stale)} - run python sync_data.py", file=sys.stderr)
            return 1
        print("workflow-data.js and config-data.js are up to date")
        return 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.name} ({len(text) // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
